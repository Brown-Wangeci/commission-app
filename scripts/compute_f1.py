"""NFR-08 (F1 >= 0.85 and recall >= 0.90 on held-out test) requires F1, which
src/eval/metrics.py does not compute: the model's own evaluation reports
PR-AUC, ROC-AUC and recall at fixed precision targets only (see
docs/model_card.md's own reasoning for omitting a single-threshold accuracy
or F1 headline). This script computes F1 the same way, on the same committed,
calibrated out-of-fold predictions, so NFR-08's traceability row rests on a
reproducible, committed script rather than an ad hoc calculation.

Usage: python -m scripts.compute_f1

Reads outputs/multiseed_predictions.parquet (gitignored; regenerated by
src/eval/multiseed_results.py's own pipeline) and the chosen calibration
method from outputs/calibration_choice.csv, exactly as
src/eval/multiseed_results.py does. Writes outputs/f1_summary_by_seed.csv and
outputs/f1_summary.csv for t7_none (deployed T7) and t0_none (deployed T0).

Best-achievable F1 is an upper bound: its threshold is chosen on the same
predictions it is then scored against, which no deployed operating point
does (the deployed bands are set from the cost model, not from maximising
F1 on held-out predictions). It is reported because NFR-08 asks for F1, not
because it is a deployable number.
"""

from __future__ import annotations

from typing import Tuple

import numpy as np
import pandas as pd
from sklearn.metrics import precision_recall_curve

from src.eval.calibration import load_predictions
from src.eval.metrics import recall_at_threshold, threshold_at_precision
from src.generator import config as config_module

OUTPUT_DIR = config_module.REPO_ROOT / "outputs"
MODELS = ["t7_none", "t0_none"]
RECALL_TARGET = 0.90
PRECISION_TARGET = 0.90


def best_f1(labels: np.ndarray, scores: np.ndarray) -> Tuple[float, float, float]:
    """Highest F1 over all thresholds, with its precision and recall.

    An upper bound: the threshold is fitted on the same predictions it is
    scored against (see module docstring).
    """
    precision, recall, _ = precision_recall_curve(labels, scores)
    denom = precision + recall
    f1 = np.divide(2 * precision * recall, denom, out=np.zeros_like(denom), where=denom > 0)
    best = int(np.argmax(f1))
    return float(f1[best]), float(precision[best]), float(recall[best])


def threshold_at_recall(labels: np.ndarray, scores: np.ndarray, target: float) -> float | None:
    """Highest-precision threshold whose recall reaches the target, or None if none does.

    The mirror of metrics.threshold_at_precision: recall falls as the
    threshold rises, so among thresholds reaching the target recall, the
    highest threshold gives the highest precision.
    """
    precision, recall, thresholds = precision_recall_curve(labels, scores)
    reachable = recall[:-1] >= target
    if not reachable.any():
        return None
    best = int(np.argmax(np.where(reachable, precision[:-1], -1.0)))
    return float(thresholds[best])


def precision_at_threshold(labels: np.ndarray, scores: np.ndarray, threshold: float | None) -> float:
    positives_flagged = scores >= threshold if threshold is not None else np.zeros_like(scores, dtype=bool)
    if threshold is None or not positives_flagged.any():
        return 0.0
    return float(labels[positives_flagged].mean())


def f1_at(precision: float, recall: float) -> float:
    return 0.0 if precision + recall == 0 else 2 * precision * recall / (precision + recall)


def per_seed_row(model: str, seed: int, labels: np.ndarray, scores: np.ndarray) -> dict:
    f1_best, f1_best_precision, f1_best_recall = best_f1(labels, scores)

    recall_threshold = threshold_at_recall(labels, scores, RECALL_TARGET)
    precision_at_r90 = precision_at_threshold(labels, scores, recall_threshold)
    recall_at_r90 = recall_at_threshold(labels, scores, recall_threshold)  # the achieved recall, >= target
    f1_at_r90 = f1_at(precision_at_r90, recall_at_r90)

    precision_threshold = threshold_at_precision(labels, scores, PRECISION_TARGET)
    recall_at_p90 = recall_at_threshold(labels, scores, precision_threshold)

    return {
        "model": model,
        "seed": seed,
        "best_f1": f1_best,
        "best_f1_precision": f1_best_precision,
        "best_f1_recall": f1_best_recall,
        "precision_at_recall90": precision_at_r90,
        "recall_at_recall90_threshold": recall_at_r90,
        "f1_at_recall90": f1_at_r90,
        "recall_at_precision90": recall_at_p90,
    }


def main() -> None:
    method = str(pd.read_csv(OUTPUT_DIR / "calibration_choice.csv")["chosen_method"].iloc[0])
    predictions = load_predictions()

    rows = []
    for model in MODELS:
        for seed, group in predictions[predictions["model"] == model].groupby("seed"):
            labels = group["label"].to_numpy()
            scores = group[method].to_numpy(dtype=float)
            rows.append(per_seed_row(model, int(seed), labels, scores))
    by_seed = pd.DataFrame(rows).sort_values(["model", "seed"]).reset_index(drop=True)
    by_seed.to_csv(OUTPUT_DIR / "f1_summary_by_seed.csv", index=False, float_format="%.6g")

    metrics = [c for c in by_seed.columns if c not in ("model", "seed")]
    summary = by_seed.groupby("model")[metrics].agg(["mean", "std"])
    summary.columns = [f"{metric}_{stat}" for metric, stat in summary.columns]
    summary = summary.reset_index()
    summary.to_csv(OUTPUT_DIR / "f1_summary.csv", index=False, float_format="%.6g")

    pd.set_option("display.width", 240)
    print(f"scores: {method} calibrated, seeds: {sorted(predictions['seed'].unique())}")
    print(by_seed.to_string(index=False))
    print()
    print(summary.to_string(index=False))
    print()
    for _, row in summary.iterrows():
        print(
            f"{row['model']}: best F1 {row['best_f1_mean']:.3f} (sd {row['best_f1_std']:.3f}) "
            f"at precision {row['best_f1_precision_mean']:.3f}, recall {row['best_f1_recall_mean']:.3f}; "
            f"recall at 90% precision {row['recall_at_precision90_mean']:.3f} (sd {row['recall_at_precision90_std']:.3f}); "
            f"precision at 90% recall {row['precision_at_recall90_mean']:.3f} (sd {row['precision_at_recall90_std']:.3f}), "
            f"F1 there {row['f1_at_recall90_mean']:.3f} (sd {row['f1_at_recall90_std']:.3f})"
        )
    print()
    print("NFR-08 needs F1 >= 0.85 with recall >= 0.90, i.e. precision >= 0.805 at that recall.")


if __name__ == "__main__":
    main()
